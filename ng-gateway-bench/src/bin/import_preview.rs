use clap::Parser;
use ng_gateway_sdk::{DriverSchemas, FieldError, FlattenEntity, ValidatedRow, ValidationCode};
use std::{collections::HashMap, fs, io::Cursor, time::Instant};

/// Benchmark tool for Excel import preview performance.
///
/// This binary is intended to reproduce and measure the CPU cost of:
/// - parsing an `.xlsx` file
/// - converting rows into JSON maps
/// - validating + normalizing rows using UI schema rules
/// - performing additional device-level consistency checks (DevicePoints)
///
/// NOTE: This binary reads driver metadata JSON from the linked southward driver crate via the
/// C-ABI symbol generated by `ng_driver_factory!`.
#[derive(Debug, Parser)]
#[command(author, version, about)]
struct Cli {
    /// Path to the `.xlsx` file.
    #[arg(
        long,
        default_value = "generated/modbus-point-tables/modbus-device-points-scenario-3.xlsx"
    )]
    xlsx: String,
}

#[cfg(feature = "modbus")]
use ng_driver_modbus as _;
#[cfg(feature = "opcua")]
use ng_driver_opcua as _;

// FFI symbols exported by exactly one linked driver (see `ng-gateway-bench` feature flags).
extern "C" {
    fn ng_driver_metadata_json_ptr(out_ptr: *mut *const u8, out_len: *mut usize);
    fn ng_driver_type() -> *const ::std::os::raw::c_char;
}

fn main() -> anyhow::Result<()> {
    tracing_subscriber::fmt()
        .with_max_level(tracing::Level::INFO)
        .init();

    let cli = Cli::parse();
    let xlsx_path = cli.xlsx;

    let t0 = Instant::now();
    let schemas = load_driver_schemas_from_ffi()?;
    let t_schemas = t0.elapsed();

    let t1 = Instant::now();
    let bytes = fs::read(&xlsx_path)?;
    let t_read = t1.elapsed();

    let entity = FlattenEntity::DevicePoints;

    // Parse + validate meta + validate rows (this matches the web preview path).
    let t2 = Instant::now();
    let template = schemas.build_template(entity, "zh-CN");
    let (metadata, rows) = template.read_with_meta_from_reader(Cursor::new(bytes))?;
    let t_parse = t2.elapsed();

    let driver_type = unsafe { cstr_to_string(ng_driver_type()) };
    metadata.validate(&driver_type, entity)?;
    let template = schemas.build_template(entity, &metadata.locale);

    let t3 = Instant::now();
    let total = rows.len();
    let (valids, errors, warn_count) = template.validate_and_normalize_rows(rows, &metadata.locale);
    let group_errors = validate_device_group_consistency(&valids);
    let t_validate = t3.elapsed();

    let mut all_errors = errors;
    all_errors.extend(group_errors);

    // Deduplicate invalid rows by row index.
    let mut invalid_rows = std::collections::HashSet::with_capacity(all_errors.len());
    for e in &all_errors {
        invalid_rows.insert(e.row);
    }

    tracing::info!(
        driver_type = driver_type,
        xlsx = xlsx_path,
        total_rows = total,
        valid = total.saturating_sub(invalid_rows.len()),
        invalid = invalid_rows.len(),
        warn = warn_count,
        schemas_ms = t_schemas.as_millis(),
        read_ms = t_read.as_millis(),
        parse_ms = t_parse.as_millis(),
        validate_ms = t_validate.as_millis(),
        "import preview benchmark done"
    );

    Ok(())
}

/// Load `DriverSchemas` from the driver-exported metadata JSON bytes.
fn load_driver_schemas_from_ffi() -> anyhow::Result<DriverSchemas> {
    let mut ptr: *const u8 = std::ptr::null();
    let mut len: usize = 0;
    unsafe { ng_driver_metadata_json_ptr(&mut ptr as *mut *const u8, &mut len as *mut usize) };
    if ptr.is_null() || len == 0 {
        anyhow::bail!("driver returned empty metadata json");
    }
    let bytes = unsafe { std::slice::from_raw_parts(ptr, len) };
    Ok(serde_json::from_slice::<DriverSchemas>(bytes)?)
}

/// Convert a C string pointer into a Rust `String`.
fn cstr_to_string(ptr: *const ::std::os::raw::c_char) -> String {
    if ptr.is_null() {
        return String::new();
    }
    unsafe { std::ffi::CStr::from_ptr(ptr).to_string_lossy().to_string() }
}

/// Validate device-level consistency constraints for `FlattenEntity::DevicePoints`.
///
/// This is identical in spirit to the web `preview` validation:
/// - `device_name` required
/// - per `device_name`, `device_type` must be consistent
/// - per `device_name`, `device_driver_config` must be consistent
fn validate_device_group_consistency(rows: &[ValidatedRow]) -> Vec<FieldError> {
    use serde_json::Value as Json;

    struct DeviceRef {
        device_type: Option<String>,
        device_driver_config: Json,
    }

    let mut refs: HashMap<String, DeviceRef> = HashMap::new();
    let mut errors: Vec<FieldError> = Vec::new();

    for row in rows {
        let device_name = row
            .values
            .get("device_name")
            .and_then(|v| v.as_str())
            .unwrap_or_default();

        if device_name.is_empty() {
            errors.push(FieldError {
                row: row.row_index,
                field: "device_name".to_string(),
                code: ValidationCode::Required,
                message: "device_name is required".to_string(),
            });
            continue;
        }

        let current_device_type = row.values.get("device_type").and_then(|v| v.as_str());
        let current_device_config = row.values.get("device_driver_config");

        if let Some(existing) = refs.get(device_name) {
            let ref_device_type = existing.device_type.as_deref();
            if current_device_type != ref_device_type {
                errors.push(FieldError {
                    row: row.row_index,
                    field: "device_type".to_string(),
                    code: ValidationCode::TypeMismatch,
                    message: format!(
                        "device_type mismatch: expected {:?}, got {:?} for device {}",
                        ref_device_type, current_device_type, device_name
                    ),
                });
            }

            let config_mismatch = match current_device_config {
                Some(v) => v != &existing.device_driver_config,
                None => !matches!(
                    existing.device_driver_config,
                    Json::Object(ref m) if m.is_empty()
                ),
            };
            if config_mismatch {
                errors.push(FieldError {
                    row: row.row_index,
                    field: "device_driver_config".to_string(),
                    code: ValidationCode::TypeMismatch,
                    message: format!("device_driver_config mismatch for device {}", device_name),
                });
            }
        } else {
            let ref_device_type = current_device_type.map(|s| s.to_string());
            let ref_device_config = current_device_config
                .cloned()
                .unwrap_or(Json::Object(serde_json::Map::new()));
            refs.insert(
                device_name.to_string(),
                DeviceRef {
                    device_type: ref_device_type,
                    device_driver_config: ref_device_config,
                },
            );
        }
    }

    errors
}
